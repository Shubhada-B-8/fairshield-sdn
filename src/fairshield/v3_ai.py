"""V3 AI components: supervised traffic risk model and network telemetry features.

The bundled training data is generated by the existing FairShield simulator.
This is a reproducible prototype model, not a model trained on real 5G traces.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable

from .models import FlowSample
from .simulator import SCENARIOS, generate_window


FEATURE_NAMES = (
    "pps", "bps", "syn_ratio", "unique_dst_ports",
    "avg_packet_bytes", "window_total_pps",
)


def feature_vector(sample: FlowSample, window_total_pps: float) -> list[float]:
    return [
        float(sample.pps),
        float(sample.bps),
        float(sample.syn_ratio),
        float(sample.unique_dst_ports),
        float(sample.avg_packet_bytes),
        float(window_total_pps),
    ]


@dataclass
class AIRiskDetector:
    """Random-forest detector trained from labelled synthetic source observations."""
    model: object
    threshold: float = 0.50

    @classmethod
    def train_synthetic(cls, seed: int = 41, windows_per_scenario: int = 80):
        try:
            from sklearn.ensemble import RandomForestClassifier
        except ImportError as exc:
            raise RuntimeError(
                'V3 AI requires scikit-learn. Install with: python -m pip install -e ".[ml]"'
            ) from exc

        import random
        rng = random.Random(seed)
        X, y = [], []
        for scenario in SCENARIOS:
            for window in range(windows_per_scenario):
                samples = generate_window(window, scenario, rng)
                total = sum(s.pps for s in samples)
                for sample in samples:
                    X.append(feature_vector(sample, total))
                    y.append(1 if sample.label == "attack" else 0)

        # Add live-like UDP flood and legitimate bulk-traffic examples.
        # These complement the simulator's SYN-flood and multi-port attacks.
        for _scenario in SCENARIOS:
            for _window in range(windows_per_scenario):
                for _ in range(4):
                    # High-rate UDP flood: low SYN ratio, few destination ports.
                    pps = rng.uniform(2500, 6500)
                    avg_bytes = rng.uniform(1300, 1512)
                    syn_ratio = rng.uniform(0.0, 0.01)
                    ports = rng.randint(1, 4)
                    total_pps = pps * rng.uniform(1.0, 1.25)
                    X.append([
                        pps, pps * avg_bytes * 8, syn_ratio,
                        ports, avg_bytes, total_pps,
                    ])
                    y.append(1)

                    # Legitimate bulk UDP: high throughput, lower source rate.
                    pps = rng.uniform(250, 1700)
                    avg_bytes = rng.uniform(900, 1500)
                    syn_ratio = rng.uniform(0.0, 0.03)
                    ports = rng.randint(1, 3)
                    total_pps = pps * rng.uniform(1.0, 2.5)
                    X.append([
                        pps, pps * avg_bytes * 8, syn_ratio,
                        ports, avg_bytes, total_pps,
                    ])
                    y.append(0)

        model = RandomForestClassifier(
            n_estimators=160, max_depth=10, min_samples_leaf=2,
            class_weight="balanced", random_state=seed, n_jobs=-1,
        )
        model.fit(X, y)
        return cls(model=model)

    def predict(self, sample: FlowSample, window_total_pps: float) -> tuple[bool, float]:
        features = [feature_vector(sample, window_total_pps)]
        probabilities = self.model.predict_proba(features)[0]
        classes = list(self.model.classes_)
        attack_index = classes.index(1)
        score = float(probabilities[attack_index])
        return score >= self.threshold, score
